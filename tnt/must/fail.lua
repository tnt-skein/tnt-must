--- Отказ: что в нём написано и на кого он указывает.
---
--- Два решения, ради которых модуль и заведён, и одна ловушка, которую
--- они не закрывают.
---
--- **Место в сообщении принадлежит вызывающему.** `error(message, level)`
--- стоит ровно в одном месте на весь пакет — в замыкании, которое
--- возвращает `raising`, и это замыкание прикладной код зовёт напрямую;
--- уровень по умолчанию — его вызывающий. Бросай каждая проверка сама,
--- глубина поехала бы у тех, что собраны из других (`optional.string`,
--- `all.string`), и человек увидел бы строку внутри tnt-must вместо
--- своей — то есть от проверки стало бы хуже, чем без неё. Поэтому
--- проверки ничего не бросают: они возвращают текст отказа либо nil,
--- а бросает один общий переходник. Сам уровень — аргумент `raising`, а не
--- константа: помощник, который заворачивает проверку (`local function
--- need_tag(v) must.string(v, 'метка') end`), виноват не сам, и чинить
--- надо строку, где его позвали. Считается уровень как у `error`: 1 —
--- строка с проверкой, 2 — вызывающий той функции, в которой она стоит;
--- ушедший глубже стека оставляет сообщение без места — как и `error`.
---
--- **Имя аргумента — часть сообщения.** «строка, а не число» бесполезно, когда
--- аргументов пять; «метка журнала — строка, а не число» говорит, что чинить.
--- Лад тот же, что уже сложился в репозитории: «<аргумент> — <чего ждали>,
--- а не <что пришло>».
---
--- **Хвостовой вызов кадра не оставляет** — проверено на 3.8: LuaJIT
--- выбрасывает кадр `return must.x(...)` целиком, и `debug.getinfo` следа
--- не видит. Уровень исчезнувший кадр не вернёт ничем: `return must.x(...)`
--- показывает на вызывающего той функции, где стоит проверка, а
--- `local v = must.x(...)` — на саму строку. Это ловушка вызывающего,
--- и пакет о ней только предупреждает — в `docs/must.md`.
---
--- Тип значения называется по-русски, а не как у `type`: сообщение целиком
--- на одном языке, и «строка, а не number» посреди русской фразы спотыкает.
---
--- **Бросок без места — тоже здесь, и тоже один.** `raise` бросает значение
--- как есть, с уровнем 0: так отказывают пакеты, чей текст уходит оператору
--- в alerts или сверяется целиком, и место в исходнике там только мешает.
--- Держать его в каждом пакете значило бы держать и одинаковое исключение
--- мутационного гейта на каждый: уровни 0 и -1 в Lua неотличимы.

local utf8 = require('utf8')

local Module = {}

--- Как назвать аргумент, которому имени не дали.
Module.DEFAULT_NAME = 'значение'

--- Уровень вины, когда его не задали: строка, на которой стоит проверка.
Module.DEFAULT_LEVEL = 1

--- Сколько знаков значения показывать в сообщении.
---
--- Предел нужен потому, что проверку зовут и на теле запроса: строка
--- в мегабайт, вывалившаяся в журнал целиком, прячет само сообщение.
Module.SHOWN = 40

--- Тип значения по-русски. Перечислены все, какие бывают у LuaJIT.
local KINDS = {
    ['nil'] = 'nil',
    boolean = 'логическое значение',
    number = 'число',
    string = 'строка',
    table = 'таблица',
    ['function'] = 'функция',
    userdata = 'userdata',
    cdata = 'cdata',
    thread = 'сопрограмма',
}

--- Имя аргумента в сообщении; безымянный называется «значение».
---@param name string|nil
---@return string
function Module.named(name)
    return name or Module.DEFAULT_NAME
end

--- Тип значения по-русски.
---
--- `box.NULL` назван по имени, а не типом: это cdata, равный `nil`, и так
--- приходит `null` из JSON и msgpack. «а не cdata» о нём не говорит
--- ничего, а «а не box.NULL» сразу показывает, откуда взялось значение.
---@param value any
---@return string
function Module.kind(value)
    if type(value) == 'cdata' and value == nil then
        return 'box.NULL'
    end

    return KINDS[type(value)]
end

--- Имя аргумента не прикладного кода, а самой проверки: границы, образца,
--- перечня допустимых.
---
--- Проверка проверяет и свои аргументы, и отказ о них обязан отличаться
--- от отказа о данных: «нижняя граница для «вес» — число, а не nil» велит
--- чинить строку с проверкой, а «вес — число, а не nil» отправил бы искать
--- в данных то, чего там нет. Забытый аргумент проверки иначе всплывает
--- сравнением с nil где-то внутри пакета — ровно тем, ради чего пакет
--- и написан.
---@param role string Чем этот аргумент приходится проверке
---@param name string|nil Имя проверяемого аргумента
---@return string
function Module.about(role, name)
    return ('%s для «%s»'):format(role, Module.named(name))
end

--- Строка не длиннее предела, с многоточием вместо хвоста.
---
--- Длина считается в знаках: «Узел» — это четыре знака и восемь байтов,
--- и байтовый предел обрезал бы кириллицу вдвое раньше, чем ждёт глаз.
--- У строки с битыми байтами знаков не сосчитать — такая меряется
--- и режется байтами: она уже испорчена, и обрубок буквы в сообщении
--- ничего не ухудшит.
---@param text string
---@return string
local function shorten(text)
    local counted = utf8.len(text) or #text

    if counted <= Module.SHOWN then
        return text
    end

    -- Начало среза — отрицательным индексом, а не единицей: у записи
    -- `sub(text, 1, n)` мутанты `0` и `1-1` дают ту же строку, и убить их
    -- нечем, а у `-counted` единственный мутант `+counted` не проходит
    -- загрузку. Ответ тот же: сюда доходит только непустая строка, а
    -- у битой строки байтов не меньше, чем знаков, и слишком далёкое
    -- начало `utf8.sub` прижимает к первому знаку.
    local head = utf8.sub(text, -counted, Module.SHOWN)

    return head .. '…'
end

--- Значение в сообщении: то, что пришло, в читаемом виде.
---
--- Строка берётся в кавычки, чтобы «а не «3»» отличалось от «а не 3»:
--- иначе аргумент-строка и аргумент-число выглядят одинаково, а чинить их надо
--- по-разному. Таблица и функция показываются типом: печатать адрес
--- в памяти человеку незачем. А вот cdata печатается как есть: у чисел,
--- uuid, decimal и datetime `tostring` показывает само значение
--- (`-1LL`, `1.5`, дату), и «а не cdata» рядом с ними ничего не сказало
--- бы о том, чем значение не годится.
---@param value any
---@return string
function Module.show(value)
    if type(value) == 'string' then
        return ('«%s»'):format(shorten(value))
    end

    if type(value) == 'cdata' then
        if value == nil then
            return Module.kind(value)
        end

        return shorten(tostring(value))
    end

    -- NaN печатается по-разному на разных сборках («nan», «-nan»), и это
    -- лишний повод усомниться в своих глазах посреди и без того неприятного
    -- сообщения.
    if value ~= value then
        return 'NaN'
    end

    if type(value) == 'number' or type(value) == 'boolean' then
        return tostring(value)
    end

    return Module.kind(value)
end

--- Текст отказа: аргумент, чего ждали, что пришло.
---@param name string|nil Как назвать аргумент
---@param expected string Чего ждали
---@param got string Что пришло — уже готовой строкой
---@return string
function Module.text(name, expected, got)
    return ('%s — %s, а не %s'):format(Module.named(name), expected, got)
end

--- Проверка, которая бросает, из проверки, которая объясняет.
---
--- Возвращается само значение: `local tag = must.string(opts.tag, 'метка')`
--- проверяет и присваивает одной строкой, и проверку незачем писать
--- отдельным предложением выше.
---
--- Уровень здесь не проверяется: `raising` зовёт фасад, и неправильный уровень
--- он отвергает сам — отказом, который показывает на строку с `must.at`.
---@param explain fun(value: any, name: string|nil, ...: any): string|nil
---@param level integer|nil Уровень вины; без него — строка с проверкой
---@return fun(value: any, name: string|nil, ...: any): any
function Module.raising(explain, level)
    -- Единица сверху — кадр самого замыкания: для `error` уровень 1 — это
    -- оно, а вызывающий отсчитывает свой уровень 1 от собственной строки.
    local depth = (level or Module.DEFAULT_LEVEL) + 1

    return function(value, name, ...)
        local complaint = explain(value, name, ...)

        if complaint ~= nil then
            error(complaint, depth)
        end

        return value
    end
end

--- Бросает значение как есть: без места вызова и без обёртки.
---
--- Для ошибки программиста, у которой место в сообщении ничего не
--- объясняет: текст уходит оператору в alerts конфигурации или сверяется
--- целиком, а приписка «файл:строка:» указала бы сюда, а не на виновника.
--- Строка остаётся строкой, объект отказа — тем же объектом.
---
--- Помощник один на репозиторий нарочно. Мутант уровня `-1` неотличим
--- от нуля — ни тот, ни другой места не приписывают, — и исключение
--- гейта на него стоит на одной этой строке, а не в каждом пакете.
---@param value any Что бросить
---@return never
function Module.raise(value)
    error(value, 0)
end

return Module
